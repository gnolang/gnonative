// Extracts the buf-free `*Json` type aliases + the ErrCode enum from the protoc-gen-es output
// (api/gen/es/*.ts, generated with json_types=true) into a single self-contained, zero-import
// file: expo/src/native/types.gen.ts.
//
// The `*Json` types are the plain-JSON shapes that go over the mobile bridge on the /native path
// (int64 -> string, bytes -> base64 string, camelCase / proto json_name fields, optional). They
// reference only each other and ErrCodeJson, so the extracted file needs no imports and pulls in no
// @bufbuild/@connectrpc runtime.
//
// Usage: node extract-json-types.mjs [inputDir] [outputFile]
//   inputDir   defaults to <repo>/api/gen/es
//   outputFile defaults to <repo>/expo/src/native/types.gen.ts

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

const inputDir = process.argv[2]
  ? path.resolve(process.argv[2])
  : path.resolve(__dirname, "../../api/gen/es");
const outputFile = process.argv[3]
  ? path.resolve(process.argv[3])
  : path.resolve(__dirname, "../src/native/types.gen.ts");

// Files are processed in this order so cross-referenced types resolve top-to-bottom for readers.
const inputFiles = ["gnonativetypes_pb.ts", "rpc_pb.ts"];

const isDeclStart = (line) =>
  /^export type \w+Json\s*=/.test(line) || /^export enum ErrCode\b/.test(line);

// Returns the index of the first line of the contiguous /** ... */ doc comment ending at line i-1,
// or i if there is no such comment.
function commentStart(lines, i) {
  if (i <= 0) return i;
  if (!lines[i - 1].trim().endsWith("*/")) return i;
  let j = i - 1;
  while (j >= 0 && !lines[j].trim().startsWith("/**")) j--;
  return j >= 0 ? j : i;
}

// Returns the index of the last line of the declaration starting at line i.
function declEnd(lines, i) {
  if (lines[i].includes("{")) {
    let depth = 0;
    for (let k = i; k < lines.length; k++) {
      for (const ch of lines[k]) {
        if (ch === "{") depth++;
        else if (ch === "}") depth--;
      }
      if (depth === 0) return k;
    }
    return lines.length - 1;
  }
  // Single statement (e.g. the ErrCodeJson string union): run to the line ending with ';'.
  let k = i;
  while (k < lines.length && !lines[k].trimEnd().endsWith(";")) k++;
  return k;
}

const blocks = [];
for (const file of inputFiles) {
  const full = path.join(inputDir, file);
  const text = fs.readFileSync(full, "utf8");
  const lines = text.split("\n");
  let i = 0;
  while (i < lines.length) {
    if (isDeclStart(lines[i])) {
      const start = commentStart(lines, i);
      const end = declEnd(lines, i);
      blocks.push(lines.slice(start, end + 1).join("\n"));
      i = end + 1;
    } else {
      i++;
    }
  }
}

if (blocks.length === 0) {
  console.error(
    `extract-json-types: no *Json types found in ${inputDir}. Did you generate es with json_types=true?`,
  );
  process.exit(1);
}

const header = `// @generated by expo/scripts/extract-json-types.mjs from api/gen/es. DO NOT EDIT.
//
// Buf-free plain-JSON type aliases for the @gnolang/gnonative/native entry point. These mirror the
// protobuf JSON encoding used over the mobile bridge: int64 as string, bytes as base64 string,
// fields use the proto json_name (camelCase / PascalCase), and all fields are optional.
/* eslint-disable */
`;

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, header + "\n" + blocks.join("\n\n") + "\n");
console.log(
  `extract-json-types: wrote ${blocks.length} type blocks to ${path.relative(process.cwd(), outputFile)}`,
);
